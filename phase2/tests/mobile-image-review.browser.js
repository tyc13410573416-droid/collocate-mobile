async (page) => {
  const errors=[];
  page.on('pageerror',error=>errors.push(error.message));
  const assert=(ok,message)=>{if(!ok)throw new Error(message);};
  const folder='C:/Users/tyc/Documents/ChatGPT/华为/交付截图/移动端分步_20261125';
  await page.setViewportSize({width:390,height:844});
  await page.goto('http://127.0.0.1:5052/');
  await page.locator('#reportFile').setInputFiles('docs/static/assets/medical-demo/sample-05-liver-panel.png');
  const filename=await page.locator('#reportFile').inputValue();
  await page.locator('#submitButton').click();
  assert(await page.locator('#loadingState').isVisible(),'real image loading visible');
  assert(!await page.locator('#analyzeForm').isVisible(),'image input hidden');
  await page.waitForFunction(()=>!document.getElementById('submitButton').disabled&&!document.getElementById('resultPanel').classList.contains('hidden'),null,{timeout:180000});
  assert(await page.locator('#resultPanel').getAttribute('data-gate')==='review','real OCR is held for review');
  assert((await page.locator('#environmentLabel').textContent()).includes('图片解读'),'image result is labelled honestly');
  assert(await page.evaluate(()=>scrollY<2),'real image result starts at top');
  await page.screenshot({path:folder+'/06-真实照片识别与复核.png',animations:'disabled'});
  const transcript=await page.locator('#imageTranscriptText').textContent();
  await page.locator('#mobileOriginal > summary').click();
  assert(await page.locator('#assetPreviewImage').isVisible(),'original image available in result view');
  assert(await page.locator('#assetPreviewImage').evaluate(el=>el.naturalWidth>0),'original image rendered');
  await page.locator('#mobileOriginal > summary').click();
  await page.locator('#editImageValues').click();
  const alt=page.locator('.image-review-row[data-code="ALT"]');
  await alt.locator('[data-field="value"]').fill('16.0');
  await alt.locator('[data-field="unit"]').fill('IU/L');
  await alt.locator('[data-field="confirmed"]').check();
  await page.locator('#reviewScopeConfirmed').check();
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),'review form fits mobile');
  await page.locator('#submitImageReview').click();
  await page.waitForFunction(()=>document.getElementById('gateBadge').textContent==='信息待补充'&&!document.getElementById('submitButton').disabled);
  await page.locator('#completeImageInfo').click();
  assert(await alt.locator('[data-field="confirmed"]').isChecked(),'confirmed ALT survives missing-info follow-up');
  await page.locator('[data-review-sex="男"]').click();
  await page.waitForFunction(()=>document.getElementById('resultPanel').dataset.gate==='pass'&&!document.getElementById('submitButton').disabled);
  assert(await page.locator('#metrics .metric').count()===1,'only confirmed ALT passes');
  assert((await page.locator('#metrics').textContent()).includes('16'),'actual normalized reading shown');
  assert(await page.locator('#imageTranscriptText').textContent()===transcript,'original OCR preserved');
  assert(!await page.locator('#analyzeForm').isVisible(),'manual review stays on result step');
  await page.screenshot({path:folder+'/07-真实照片人工复核后结果.png',animations:'disabled'});
  await page.locator('.metric-source-button').click();
  assert(await page.locator('#metricSourceDialog').isVisible(),'sources remain tappable');
  await page.screenshot({path:folder+'/08-手机端指标来源.png',animations:'disabled'});
  await page.locator('#closeMetricSource').click();
  await page.locator('#mobileBack').click();
  assert(await page.locator('#reportFile').inputValue()===filename,'selected photo survives return');
  assert(await page.locator('#assetPreview').evaluate(el=>Boolean(el.closest('#analyzeForm'))),'original preview returns to input');
  assert(await page.locator('#patientGender').inputValue()==='男','test-supplied gender preserved');
  assert(!await page.locator('.output-card').isVisible(),'result is not stacked under input');
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),'mobile no overflow');
  assert(!errors.length,errors.join(';'));
  return {passed:true,realImage:true,mobileManualReview:true,originalImageAvailable:true,selectedImagePreserved:true,genderFollowup:true,sourceTap:true,errors};
}
